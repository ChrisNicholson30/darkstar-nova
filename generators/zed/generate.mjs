export async function generateZed({ tokens, syntax, variants }) {
  const themeFamily = {
    $schema: "https://zed.dev/schema/themes/v0.2.0.json",
    name: tokens.family,
    author: "Chris Nicholson",
    themes: variants.map((variant) => ({
      name: variant.name,
      appearance: "dark",
      style: buildStyle(variant.palette, syntax),
    })),
  };

  const outputDirectory = resolve(repositoryRoot, "themes");
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    resolve(outputDirectory, "darkstar-nova.json"),
    `${JSON.stringify(themeFamily, null, 2)}\n`,
  );
}
